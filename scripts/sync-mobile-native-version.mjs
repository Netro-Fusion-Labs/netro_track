#!/usr/bin/env node
/**
 * Sync apps/mobile/package.json SemVer → Android / iOS native version fields
 * and apps/mobile/src/shared/constants/appVersion.ts.
 *
 * Exits non-zero if post-write assertions fail (no silent partial updates).
 *
 * Env:
 *   MOBILE_VERSION_CODE — optional absolute build integer (else max(current)+1)
 *   MOBILE_ROOT — optional override of apps/mobile path (for tests)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

export function resolveMobilePaths(mobileRoot) {
  return {
    packageJson: path.join(mobileRoot, 'package.json'),
    gradle: path.join(mobileRoot, 'android/app/build.gradle'),
    pbxproj: path.join(mobileRoot, 'ios/mobile.xcodeproj/project.pbxproj'),
    appVersionTs: path.join(mobileRoot, 'src/shared/constants/appVersion.ts'),
  };
}

export function readPackageVersion(packageJsonPath) {
  const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
  if (!pkg.version || typeof pkg.version !== 'string') {
    throw new Error(`Missing version in ${packageJsonPath}`);
  }
  return pkg.version;
}

export function parseAndroidVersions(gradleContent) {
  const nameMatch = gradleContent.match(/versionName\s+"([^"]+)"/);
  const codeMatch = gradleContent.match(/versionCode\s+(\d+)/);
  return {
    versionName: nameMatch ? nameMatch[1] : null,
    versionCode: codeMatch ? Number.parseInt(codeMatch[1], 10) : null,
  };
}

export function parseIosVersions(pbxContent) {
  const marketing = [...pbxContent.matchAll(/MARKETING_VERSION\s*=\s*([^;]+);/g)].map((m) =>
    m[1].trim(),
  );
  const builds = [...pbxContent.matchAll(/CURRENT_PROJECT_VERSION\s*=\s*([^;]+);/g)].map((m) =>
    Number.parseInt(m[1].trim(), 10),
  );
  return { marketingVersions: marketing, buildNumbers: builds };
}

export function nextBuildNumber(androidCode, iosBuilds, envOverride) {
  if (envOverride !== undefined && envOverride !== '') {
    const n = Number.parseInt(String(envOverride), 10);
    if (!Number.isFinite(n) || n < 1) {
      throw new Error(`Invalid MOBILE_VERSION_CODE: ${envOverride}`);
    }
    return n;
  }
  const iosMax = iosBuilds.length ? Math.max(...iosBuilds.filter((n) => Number.isFinite(n))) : 0;
  const android = Number.isFinite(androidCode) ? androidCode : 0;
  return Math.max(android, iosMax, 0) + 1;
}

export function applyAndroidVersions(gradleContent, versionName, versionCode) {
  let next = gradleContent.replace(/versionName\s+"[^"]+"/, `versionName "${versionName}"`);
  next = next.replace(/versionCode\s+\d+/, `versionCode ${versionCode}`);
  return next;
}

export function applyIosVersions(pbxContent, marketingVersion, buildNumber) {
  let next = pbxContent.replace(
    /MARKETING_VERSION\s*=\s*[^;]+;/g,
    `MARKETING_VERSION = ${marketingVersion};`,
  );
  next = next.replace(
    /CURRENT_PROJECT_VERSION\s*=\s*[^;]+;/g,
    `CURRENT_PROJECT_VERSION = ${buildNumber};`,
  );
  return next;
}

export function renderAppVersionTs(version, build) {
  return `/** Generated by scripts/sync-mobile-native-version.mjs — do not edit by hand. */
export const APP_VERSION = '${version}' as const;
export const APP_BUILD = ${build} as const;
`;
}

export function assertAndroid(gradleContent, versionName, versionCode) {
  const parsed = parseAndroidVersions(gradleContent);
  if (parsed.versionName !== versionName) {
    throw new Error(
      `Android versionName mismatch: expected "${versionName}", found "${parsed.versionName}"`,
    );
  }
  if (parsed.versionCode !== versionCode) {
    throw new Error(
      `Android versionCode mismatch: expected ${versionCode}, found ${parsed.versionCode}`,
    );
  }
}

export function assertIos(pbxContent, marketingVersion, buildNumber) {
  const { marketingVersions, buildNumbers } = parseIosVersions(pbxContent);
  if (marketingVersions.length === 0) {
    throw new Error('iOS MARKETING_VERSION not found after write');
  }
  if (buildNumbers.length === 0) {
    throw new Error('iOS CURRENT_PROJECT_VERSION not found after write');
  }
  for (const v of marketingVersions) {
    if (v !== marketingVersion) {
      throw new Error(
        `iOS MARKETING_VERSION mismatch: expected "${marketingVersion}", found "${v}"`,
      );
    }
  }
  for (const b of buildNumbers) {
    if (b !== buildNumber) {
      throw new Error(
        `iOS CURRENT_PROJECT_VERSION mismatch: expected ${buildNumber}, found ${b}`,
      );
    }
  }
}

export function assertAppVersionTs(content, version, build) {
  const expected = renderAppVersionTs(version, build);
  if (content !== expected) {
    throw new Error('appVersion.ts content mismatch after write');
  }
}

/**
 * @param {{ mobileRoot: string, versionCodeEnv?: string }} opts
 */
export function syncMobileNativeVersion(opts) {
  const paths = resolveMobilePaths(opts.mobileRoot);
  for (const [key, p] of Object.entries(paths)) {
    if (key === 'appVersionTs') continue;
    if (!fs.existsSync(p)) {
      throw new Error(`Missing required file (${key}): ${p}`);
    }
  }

  const version = readPackageVersion(paths.packageJson);
  const gradleBefore = fs.readFileSync(paths.gradle, 'utf8');
  const pbxBefore = fs.readFileSync(paths.pbxproj, 'utf8');
  const android = parseAndroidVersions(gradleBefore);
  const ios = parseIosVersions(pbxBefore);
  const build = nextBuildNumber(android.versionCode, ios.buildNumbers, opts.versionCodeEnv);

  const gradleNext = applyAndroidVersions(gradleBefore, version, build);
  const pbxNext = applyIosVersions(pbxBefore, version, build);
  const appVersionNext = renderAppVersionTs(version, build);

  fs.writeFileSync(paths.gradle, gradleNext, 'utf8');
  fs.writeFileSync(paths.pbxproj, pbxNext, 'utf8');
  fs.mkdirSync(path.dirname(paths.appVersionTs), { recursive: true });
  fs.writeFileSync(paths.appVersionTs, appVersionNext, 'utf8');

  const gradleAfter = fs.readFileSync(paths.gradle, 'utf8');
  const pbxAfter = fs.readFileSync(paths.pbxproj, 'utf8');
  const appVersionAfter = fs.readFileSync(paths.appVersionTs, 'utf8');

  assertAndroid(gradleAfter, version, build);
  assertIos(pbxAfter, version, build);
  assertAppVersionTs(appVersionAfter, version, build);

  return { version, build, paths };
}

function main() {
  try {
    const mobileRoot = process.env.MOBILE_ROOT
      ? path.resolve(process.env.MOBILE_ROOT)
      : path.join(REPO_ROOT, 'apps/mobile');
    const result = syncMobileNativeVersion({
      mobileRoot,
      versionCodeEnv: process.env.MOBILE_VERSION_CODE,
    });
    console.log(
      `Synced mobile native version: ${result.version} (build ${result.build})`,
    );
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  main();
}
